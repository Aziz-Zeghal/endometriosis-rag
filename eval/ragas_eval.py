"""RAGAS (collections API): faithfulness, answer relevancy and context precision with
reference, on the in-corpus golden questions answered by the real graph.

    python -m eval.ragas_eval           # writes eval/reports/ragas.md

Both profiles run one after the other in this process (local Qdrant: one profile's index
open at a time; the backend must not be running). Needs the LLM and embedding endpoints.
"""

import asyncio
import logging
import statistics
from collections import defaultdict
from datetime import date
from pathlib import Path

from endorag_back.config.settings import Settings
from pydantic import BaseModel
from ragas.llms import llm_factory
from ragas.metrics.collections import (
    AnswerRelevancy,
    ContextPrecisionWithReference,
    Faithfulness,
)

from eval.golden import GoldenItem, load_golden
from eval.graph_run import TurnResult, profile_graph, run_items
from eval.judge import JUDGE_MODEL, RagasEmbedding, judge_client

logger = logging.getLogger(__name__)

PROFILES = ["patient", "gp"]
METRICS = ["faithfulness", "answer_relevancy", "context_precision"]
CONCURRENCY = 4
REPORT = Path(__file__).parent / "reports" / "ragas.md"


class Scored(BaseModel):
    profile: str
    item_id: str
    category: str
    wording: str
    route: str
    scores: dict[str, float | None]  # None: not answered, or the metric failed


async def score(items: list[GoldenItem], turns: list[TurnResult], settings: Settings) -> list:
    # 4096: with ragas' default (1024) the statement lists of long answers were truncated and
    # 32 of 34 faithfulness calls failed (gateway: finish_reason=length).
    llm = llm_factory(
        JUDGE_MODEL,
        provider="openai",
        client=judge_client(settings),
        temperature=0,
        max_tokens=4096,
    )
    faithfulness = Faithfulness(llm=llm)
    relevancy = AnswerRelevancy(llm=llm, embeddings=RagasEmbedding(settings))
    precision = ContextPrecisionWithReference(llm=llm)
    semaphore = asyncio.Semaphore(CONCURRENCY)

    async def safe(name: str, item_id: str, coro) -> float | None:
        try:
            return float((await coro).value)
        except Exception as exc:
            logger.warning("%s %s failed: %s", item_id, name, str(exc)[:200])
            return None

    async def one(item: GoldenItem, turn: TurnResult) -> Scored:
        scores: dict[str, float | None] = dict.fromkeys(METRICS)
        if turn.route == "question" and turn.contexts:
            async with semaphore:
                q, a, ctx = item.user_input, turn.answer, turn.contexts
                scores = {
                    "faithfulness": await safe(
                        "faithfulness",
                        item.id,
                        faithfulness.ascore(user_input=q, response=a, retrieved_contexts=ctx),
                    ),
                    "answer_relevancy": await safe(
                        "answer_relevancy", item.id, relevancy.ascore(user_input=q, response=a)
                    ),
                    "context_precision": await safe(
                        "context_precision",
                        item.id,
                        precision.ascore(
                            user_input=q, reference=item.reference, retrieved_contexts=ctx
                        ),
                    ),
                }
        logger.info("%s scored: %s", item.id, scores)
        return Scored(
            profile=settings.profile,
            item_id=item.id,
            category=item.category,
            wording=item.wording or "",
            route=turn.route,
            scores=scores,
        )

    return await asyncio.gather(*(one(i, t) for i, t in zip(items, turns, strict=True)))


def _mean(values: list[float | None]) -> str:
    kept = [v for v in values if v is not None]
    return f"{statistics.mean(kept):.2f}" if kept else "-"


def _group_rows(label: str, rows: list[Scored]) -> str:
    answered = [r for r in rows if r.route == "question"]
    cells = [_mean([r.scores[m] for r in answered]) for m in METRICS]
    return f"| {label} | {len(rows)} | {len(answered)} | {' | '.join(cells)} |"


def render(rows: list[Scored]) -> str:
    header = (
        "| Group | Questions | Answered | Faithfulness | Answer relevancy | "
        "Context precision |\n|---|---|---|---|---|---|"
    )
    lines = [
        "# RAGAS evaluation",
        "",
        f"Generated by `python -m eval.ragas_eval` on {date.today().isoformat()}, ragas "
        "collections API (`Faithfulness`, `AnswerRelevancy`, `ContextPrecisionWithReference`).",
        "",
        "- **Generator**: the real graph of each profile (Nemotron 3 Ultra, reasoning off), "
        "run in process on the in-corpus golden questions (follow-ups with their history).",
        f"- **Judge**: `{JUDGE_MODEL}` (another model family than the generator) on the same "
        "OpenAI-compatible endpoint, through `llm_factory` with an `AsyncOpenAI` client, "
        "temperature 0.",
        "- **Embeddings** (answer relevancy): `nemotron-3-embed-1b`, the retrieval embedder, "
        "behind the RAGAS embedding interface.",
        "- **Answered**: the graph went to `generate` (a refusal or clarification of an "
        "in-corpus question is a false refusal, reported in eval/reports/guardrails.md). "
        "Averages are over answered questions; a metric call that failed is left out.",
        "",
        "## Per profile",
        "",
        header,
    ]
    for profile in PROFILES:
        lines.append(_group_rows(f"**{profile}**", [r for r in rows if r.profile == profile]))
    for profile in PROFILES:
        prof = [r for r in rows if r.profile == profile]
        by_cat: dict[str, list[Scored]] = defaultdict(list)
        for r in prof:
            by_cat[r.category].append(r)
        lines += ["", f"## {profile}: per category and wording", "", header]
        lines += [_group_rows(cat, group) for cat, group in sorted(by_cat.items())]
        for wording in ("lay", "medical"):
            lines.append(
                _group_rows(f"wording: {wording}", [r for r in prof if r.wording == wording])
            )
    lines += [
        "",
        "## Per question",
        "",
        "| Profile | Question | Category | Route | Faithfulness | Answer relevancy | "
        "Context precision |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        cells = [_mean([r.scores[m]]) for m in METRICS]
        lines.append(
            f"| {r.profile} | `{r.item_id}` | {r.category} | {r.route} | {' | '.join(cells)} |"
        )
    lines += [
        "",
        "## Limits",
        "",
        "- RAGAS prompts are in English and the answers in French: read the scores as relative "
        "between configurations, not as absolute quality.",
        "- Small sample (tens of questions per profile) and one run: the generator runs at "
        "temperature 0.2, so scores move between runs.",
        "- Faithfulness counts every statement, including the fixed advice the prompt requires "
        "(« parlez-en à un médecin ») when no passage states it, which lowers the score of "
        "otherwise grounded answers.",
        "- Answer relevancy is a cosine between the question and questions the judge generates "
        "from the answer; Nemotron cosines between paraphrases sit well below 1, so the scale "
        "is compressed. Answers that decline part of a request (diagnosis, dose) are scored as "
        "less relevant by design.",
        "- Follow-up items are scored on the last message alone (the judge does not see the "
        "history).",
        "",
    ]
    return "\n".join(lines)


async def run_profile(profile: str) -> list[Scored]:
    settings = Settings(profile=profile)
    items = [i for i in load_golden(profile) if i.in_corpus]
    with profile_graph(profile) as graph:
        turns = await run_items(graph, items)
    return await score(items, turns, settings)


async def main() -> None:
    rows: list[Scored] = []
    for profile in PROFILES:
        rows += await run_profile(profile)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(render(rows), encoding="utf-8")
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s"
    )
    for name in ("httpx", "httpx2", "openai", "instructor"):
        logging.getLogger(name).setLevel(logging.WARNING)
    asyncio.run(main())
